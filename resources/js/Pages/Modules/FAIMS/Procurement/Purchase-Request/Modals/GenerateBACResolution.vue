                if (num >= 11 && num <= 13) return "th"; // Special case for 11-13
                const lastDigit = num % 10;
                switch (lastDigit) {
                    case 1: return "st";
                    case 2: return "nd";
                    case 3: return "rd";
                    default: return "th";
                    }
                };

