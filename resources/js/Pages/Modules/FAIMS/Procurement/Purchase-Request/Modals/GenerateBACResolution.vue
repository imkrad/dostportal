                let str = "";
                if (n >= 100) {
                str += ones[Math.floor(n / 100)] + " HUNDRED ";
                n %= 100;
                }
                if (n >= 11 && n <= 19) {
                str += teens[n - 11] + " ";
                return str;
                } else if (n >= 10) {
                str += tens[Math.floor(n / 10)] + " ";
                n %= 10;
                }
                if (n > 0) {
                str += ones[n] + " ";
                }
                return str;
            }

