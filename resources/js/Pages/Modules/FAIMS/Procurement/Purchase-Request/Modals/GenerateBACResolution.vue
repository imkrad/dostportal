            let chunkIndex = 0;

            while (num > 0) {
                let chunk = num % 1000;
                if (chunk > 0) {
                word = convertChunk(chunk) + thousands[chunkIndex] + " " + word;
                }
                num = Math.floor(num / 1000);
                chunkIndex++;
            }

            return word.trim();
